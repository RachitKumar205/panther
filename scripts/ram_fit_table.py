"""Phase A deliverable: predicted peak RAM per (model, uniform format, context).

Usage: uv run python scripts/ram_fit_table.py [--out docs/ram_fit_table.md]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from panther.costs.formats import bits_per_weight, candidate_formats
from panther.costs.ram import GIB, estimate_ram, uniform
from panther.models.inventory import CONFIG_DIR, build_inventory, load_geometry, load_registry

CONTEXTS = [2048, 4096]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/ram_fit_table.md")
    args = ap.parse_args()

    budgets = yaml.safe_load((CONFIG_DIR / "budgets.yaml").read_text())
    overhead = budgets["overhead_gib"]["default"]
    measured = budgets["overhead_is_measured"]
    formats = candidate_formats()

    lines = [
        "# RAM fit table",
        "",
        "Predicted peak RAM in **GiB** = weights (exact, from gguf-py block sizes) + f16 KV cache at the",
        f"given context + runtime overhead ({overhead} GiB, "
        + ("measured" if measured else "**placeholder until measured on the Pi**")
        + ").",
        "Uniform format applied to every searchable tensor including embedding and output head.",
        "",
        "Generated by `scripts/ram_fit_table.py`.",
        "",
    ]
    for m in load_registry()["models"]:
        inv = build_inventory(load_geometry(m["name"]))
        geo = inv.geometry
        lines += [
            f"## {m['name']}",
            "",
            f"{geo.n_layers} layers · hidden {geo.hidden} · MLP {geo.intermediate} · "
            f"{'tied' if geo.tied else 'untied'} embedding · KV cache "
            + " / ".join(f"{geo.kv_cache_bytes(c) / GIB:.2f} GiB @ {c}" for c in CONTEXTS),
            "",
            "| Format | bits/weight | Weights (GiB) | " + " | ".join(f"Peak @ {c}" for c in CONTEXTS) + " |",
            "|---|---|---|" + "---|" * len(CONTEXTS),
        ]
        for fmt in formats:
            row = [fmt, f"{bits_per_weight(fmt):.3f}"]
            ests = [estimate_ram(inv, uniform(inv, fmt), c, overhead) for c in CONTEXTS]
            row.append(f"{ests[0].weights / GIB:.2f}")
            row += [f"{e.total_gib:.2f}" for e in ests]
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
